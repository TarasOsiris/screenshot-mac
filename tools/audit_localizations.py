def normalized_specifiers(value: str) -> list[str]:
    specs: list[tuple[int, str, bool]] = []
    for index, match in enumerate(FORMAT_SPECIFIER_RE.finditer(value), start=1):
        if match.group(0) == "%%":
            continue
        position = int(match.group("position")) if match.group("position") else index
        specs.append((position, match.group("type"), match.group("position") is not None))
    if specs and all(positioned for _position, _type, positioned in specs):
        specs = sorted(specs, key=lambda item: item[0])
    return [f"%{specifier_type}" for _position, specifier_type, _positioned in specs]


def localized_values(localization: dict) -> list[str]:
    values: list[str] = []

    def collect(node: object) -> None:
        if isinstance(node, dict):
            string_unit = node.get("stringUnit")
            if isinstance(string_unit, dict) and isinstance(string_unit.get("value"), str):
                values.append(string_unit["value"])
            for key, value in node.items():
                if key != "stringUnit":
                    collect(value)
        elif isinstance(node, list):
            for value in node:
                collect(value)

    collect(localization)
    return values


def is_active(entry: dict, include_stale: bool) -> bool:
    return include_stale or entry.get("extractionState") != "stale"


def should_allow_verbatim(source: str) -> bool:
    if source in VERBATIM_ALLOWED:
        return True
    if not ASCII_WORD_RE.search(source):
        return True
    if source.startswith("http://") or source.startswith("https://"):
        return True
    return False


def audit(catalog: Path, include_stale: bool) -> list[str]:
    data = xcstrings_format.load(catalog)
    strings = data.get("strings", {})
    errors: list[str] = []

    for key, entry in strings.items():
        if not is_active(entry, include_stale):
            continue

        if MANUAL_PLURAL_RE.search(key):
            errors.append(f"manual plural anti-pattern in key: {key}")

        source_specs = normalized_specifiers(key)
        localizations = entry.get("localizations", {})
        for language in TARGET_LANGUAGES:
            localization = localizations.get(language)
            if not localization:
                errors.append(f"{language}: missing localization for {key}")
                continue

            values = localized_values(localization)
            if not values:
                errors.append(f"{language}: missing string value for {key}")
                continue

            for value in values:
                if PROTECTION_TOKEN_RE.search(value):
                    errors.append(f"{language}: unreplaced translation token in {key}: {value}")

                if MANUAL_PLURAL_RE.search(value):
                    errors.append(f"{language}: manual plural anti-pattern in {key}: {value}")

                value_specs = normalized_specifiers(value)
                if value_specs != source_specs:
                    errors.append(
                        f"{language}: placeholder mismatch for {key}: "
                        f"source={source_specs} translation={value_specs}"
                    )

                if value == key and not should_allow_verbatim(key):
                    errors.append(f"{language}: untranslated value for {key}")

    return errors


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--catalog", type=Path, default=CATALOG)
    parser.add_argument("--include-stale", action="store_true")
    args = parser.parse_args()

    errors = audit(args.catalog, args.include_stale)
    if errors:
        print(f"localization audit failed with {len(errors)} issue(s):", file=sys.stderr)
        for error in errors[:200]:
            print(f"- {error}", file=sys.stderr)
        if len(errors) > 200:
            print(f"... {len(errors) - 200} more", file=sys.stderr)
        return 1

    print("localization audit passed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
