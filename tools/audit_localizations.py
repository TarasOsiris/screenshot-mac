#!/usr/bin/env python3
"""Audit Screenshot Bro's app-interface String Catalog.

The catalog is generated by Xcode and populated by the translation scripts, so
this checker is intentionally read-only. It catches the localization regressions
that are easy to reintroduce from Swift code: missing target-language entries,
format placeholder drift, leaked translation-protection tokens, untranslated
English copy, and manual plural hacks such as `screenshot%@` or `image(s)`.
"""

